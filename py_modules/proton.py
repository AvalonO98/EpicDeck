"""Run Windows Epic games through Steam's own Proton.

Legendary launches a Windows title by running ``wine <exe>``; SteamOS has no
wine on ``PATH``, so the launch died with ``FileNotFoundError: 'wine'``.

Proton is on the device though (shipped by Steam, plus whatever GE builds the
user installed), and Legendary leaves a hook: ``--wine`` is nothing more than
"prepend this command to the game command line". So a *wrapper script* passed
as ``--wine`` works — Legendary runs ``<wrapper> <exe> <game args>`` and the
wrapper hands the same arguments to ``proton run``.

Two details matter and are easy to get wrong:

  * Proton must not inherit ``WINEPREFIX`` (it derives the prefix from
    ``STEAM_COMPAT_DATA_PATH`` and a stray WINEPREFIX corrupts the container
    setup), so the wrapper unsets it;
  * the compatdata directory is keyed by the *Steam shortcut appid*, which is
    what makes the prefix line up with the entry the user sees in their
    library (and lets Steam's own per-game settings apply).
"""

import os
import re

# Steam keeps Proton builds in two places: the ones it ships, and third-party
# tools dropped into `compatibilitytools.d` (GE-Proton et al).
PROTON_SEARCH_DIRS = (
    os.path.join("compatibilitytools.d"),
    os.path.join("steamapps", "common"),
)

# Alphabetically sorted builds that are not what a user wants by default.
UNSTABLE_HINTS = ("beta", "experimental", "hotfix", "nightly", "next")


def steam_root() -> str:
    """Path to the Steam installation (``~/.steam/steam`` on SteamOS)."""
    home = os.path.expanduser("~")
    for candidate in (
        os.path.join(home, ".steam", "steam"),
        os.path.join(home, ".local", "share", "Steam"),
    ):
        if os.path.isdir(os.path.join(candidate, "steamapps")):
            return candidate
    # Nothing exists yet: return the canonical path so error messages at least
    # point at where we looked.
    return os.path.join(home, ".steam", "steam")


def compatdata_dir(appid: int) -> str:
    return os.path.join(steam_root(), "steamapps", "compatdata", str(int(appid)))


def _version_key(name: str):
    """Sort key for a build name: ``GE-Proton10-25`` -> (10, 25)."""
    stripped = re.sub(r"(?i)ge-?proton|proton", "", name)
    match = re.search(r"(\d+)(?:[.\-](\d+))?", stripped)
    if not match:
        return (0, 0)
    return (int(match.group(1)), int(match.group(2) or 0))


def _entry_kind(name: str) -> str:
    lower = name.lower()
    if lower.startswith("ge-proton"):
        return "ge"
    if any(hint in lower for hint in UNSTABLE_HINTS):
        return "unstable"
    if lower.startswith("proton"):
        return "stable"
    return "other"


_KIND_RANK = {"ge": 0, "stable": 1, "other": 2, "unstable": 3}


def find_protons():
    """List installed Proton builds, best candidate first.

    Ordering follows what actually works on a Deck: a GE build beats Valve's
    bundled one (better compatibility, and it is there because the user chose
    it), then the newest stable Proton, then everything else.
    """
    root = steam_root()
    found = {}
    for rel in PROTON_SEARCH_DIRS:
        base = os.path.join(root, rel)
        try:
            names = sorted(os.listdir(base))
        except OSError:
            continue
        for name in names:
            if name.startswith("."):
                continue
            script = os.path.join(base, name, "proton")
            if not os.path.isfile(script) or not os.access(script, os.X_OK):
                continue
            found[script] = {
                "name": name,
                "path": script,
                "dir": os.path.dirname(script),
                "kind": _entry_kind(name),
                "version": _version_key(name),
            }
    builds = list(found.values())
    builds.sort(key=lambda b: (_KIND_RANK[b["kind"]], tuple(-v for v in b["version"])))
    return builds


def choose_proton(override: str = ""):
    """Best Proton build, honouring a user-selected path first."""
    override = (override or "").strip()
    if override:
        candidate = os.path.expanduser(override)
        # Accept either the build directory or the `proton` script inside it.
        if os.path.isdir(candidate):
            candidate = os.path.join(candidate, "proton")
        if os.path.isfile(candidate) and os.access(candidate, os.X_OK):
            return candidate
    builds = find_protons()
    return builds[0]["path"] if builds else ""


def wrapper_script(appid: int, proton_bin: str) -> str:
    """The ``--wine`` shim for one game."""
    root = steam_root()
    data = compatdata_dir(appid)
    return (
        "#!/bin/bash\n"
        "# Generated by EpicDeck: run Windows titles through Steam's Proton.\n"
        "# Safe to delete; the plugin recreates it on the next sync.\n"
        "unset WINEPREFIX\n"
        'export STEAM_COMPAT_CLIENT_INSTALL_PATH="%s"\n'
        'export STEAM_COMPAT_DATA_PATH="%s"\n'
        "export SteamAppId=%d\n"
        "export SteamGameId=%d\n"
        "export SteamDeck=1\n"
        'mkdir -p "$STEAM_COMPAT_DATA_PATH"\n'
        '# First run initialises the prefix here and can take a minute.\n'
        'exec "%s" waitforexitandrun "$@"\n'
        % (root, data, int(appid), int(appid), proton_bin)
    )


def write_wrapper(path: str, appid: int, proton_bin: str) -> str:
    """Write (or refresh) the wrapper script and return its path."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    content = wrapper_script(appid, proton_bin)
    # Only touch the file when the content actually changed: Steam re-reads the
    # launcher on every launch and a needless rewrite is a needless cache miss.
    try:
        with open(path, "r", encoding="utf-8") as fh:
            if fh.read() == content:
                return path
    except OSError:
        pass
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(content)
    os.chmod(path, 0o755)
    return path


def is_windows(platform_value) -> bool:
    return str(platform_value or "").strip().lower().startswith("windows")
